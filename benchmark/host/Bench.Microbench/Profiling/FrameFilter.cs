namespace Orleans.Lattice.Benchmark.Microbench.Profiling;

/// <summary>
/// Pure, allocation-light predicate that decides whether a resolved managed
/// stack frame is <em>product code worth attributing</em> or
/// <em>measurement-substrate noise</em> (test mocks, the BDN engine, the JIT
/// helpers, async-state-machine plumbing).
/// </summary>
/// <remarks>
/// <para>
/// The EventPipe symbolicator attributes every allocation / CPU sample to the
/// <em>deepest</em> named managed frame on the call stack. On the in-process
/// microbench harness that deepest frame is very frequently a NSubstitute /
/// Castle DynamicProxy thunk, a BenchmarkDotNet engine method, or a runtime
/// helper - none of which a lattice optimisation can touch. Prior optimisation
/// cycles drowned in this noise (cycles on <c>SetManyAtomic</c> and
/// <c>BulkLoad</c> measured 36-53% of top-N attributed to mock frames).
/// </para>
/// <para>
/// This filter is consulted by the symbolicator: when the deepest frame is a
/// noise frame, the walker keeps climbing toward the caller until it finds a
/// frame that <see cref="IsProductFrame"/> accepts, attributing the cost to
/// the nearest product frame instead. The default deny-list is conservative -
/// it only removes frames that are unambiguously not lattice code.
/// </para>
/// </remarks>
public static class FrameFilter
{
    /// <summary>
    /// Namespace / module prefixes that are never product code. Matched against
    /// the fully-qualified method name with <see cref="StringComparison.Ordinal"/>.
    /// </summary>
    private static readonly string[] NoiseMethodPrefixes =
    {
        // Test-double machinery injected by the in-process harness.
        "Castle.",
        "NSubstitute.",
        "ProxyGenerator",
        // The BenchmarkDotNet engine, toolchain, and generated runner.
        "BenchmarkDotNet.",
        "Orleans.Lattice.Benchmark.Microbench.Profiling.",
        // Microbench-driver auto-generated runner type emitted by BDN's
        // InProcessEmitToolchain.
        "BenchmarkDotNet.Autogenerated.",
    };

    /// <summary>
    /// Exact / prefix fragments that mark a frame as runtime / framework
    /// plumbing rather than lattice logic. Kept separate from
    /// <see cref="NoiseMethodPrefixes"/> because these are matched anywhere in
    /// the name, not just at the start (async builders are nested generic types
    /// whose user-facing prefix is the product namespace).
    /// </summary>
    private static readonly string[] NoiseMethodFragments =
    {
        "AsyncTaskMethodBuilder",
        "AsyncMethodBuilderCore",
        "AsyncValueTaskMethodBuilder",
        "System.Runtime.CompilerServices.AsyncMethodBuilder",
        "System.Threading.ExecutionContext",
        "System.Threading.Tasks.AwaitTaskContinuation",
    };

    /// <summary>
    /// Returns <see langword="true"/> when <paramref name="fullMethodName"/>
    /// names a frame the profiler should attribute cost to (i.e. it is NOT
    /// measurement-substrate noise). Null / empty / unresolved names are
    /// rejected so the symbolicator keeps climbing.
    /// </summary>
    /// <param name="fullMethodName">
    /// Fully-qualified managed method name as produced by the TraceEvent
    /// symbolicator (e.g.
    /// <c>Orleans.Lattice.VersionVector.Merge</c>).
    /// </param>
    public static bool IsProductFrame(string? fullMethodName)
    {
        if (string.IsNullOrEmpty(fullMethodName))
        {
            return false;
        }
        if (fullMethodName.StartsWith("UNMANAGED_CODE_TIME", StringComparison.Ordinal)
            || fullMethodName.StartsWith("?", StringComparison.Ordinal))
        {
            return false;
        }
        foreach (var prefix in NoiseMethodPrefixes)
        {
            if (fullMethodName.StartsWith(prefix, StringComparison.Ordinal))
            {
                return false;
            }
        }
        foreach (var fragment in NoiseMethodFragments)
        {
            if (fullMethodName.Contains(fragment, StringComparison.Ordinal))
            {
                return false;
            }
        }
        return true;
    }
}
